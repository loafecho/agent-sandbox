#!/usr/bin/env python3
"""Generate everything that derives from tools.yaml, so the lists can never drift apart:

  switchboard/generated/agents.json            tools + per-agent allow-lists for the switchboard (no token values)
  boxes/<box>/openshell/profile-<provider>.yaml  each box's OpenShell provider profile (MCP tool allow-list)
  switchboard/TOOLS.md                         the readable list of every button

Run: python3 switchboard/gen.py. Deterministic: same input, same bytes. Commit the output.

  gen.py                    regenerate everything above
  gen.py --sync-upstream    copy each upstream gateway's tools/list (its TOOLS) into upstream/<group>.json
  gen.py --check-upstream   compare those snapshots with the gateways' code now; prints CHECK-UPSTREAM diffs=N
                            (exit 1 when N > 0). Forwarded tools are served byte-identical to the snapshot.
  gen.py --check            regenerate in memory and compare with the committed files; prints GEN-CHECK
                            stale=N (exit 1 when N > 0). CI runs this.
"""
import difflib
import importlib
import json
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
# Which key each backend uses. Shown in TOOLS.md; the keys themselves live only on the switchboard VM.
BACKENDS = {
    "prometheus": "Prometheus `172.16.0.29:9090`. No key.",
    "pve": "Proxmox API `https://172.16.0.88:8006`, user `switchboard@pve`, token `sb` (PVEAuditor: read-only; privilege-separated; expires yearly). TLS trusts only the cluster's `pve-root-ca.pem`.",
    "jellyfin": "Jellyfin `http://172.16.0.91:8096`, app key `switchboard`. **Jellyfin has no read-only key, so this key is admin-level.** Read tools use a GET-only type; the one write, `POST /Library/Refresh`, sits in its own type and runs only after the approver's ✅.",
    "approvals": "The switchboard's own request store (`/var/lib/switchboard/requests.json`). No key.",
}
TIERS = ("read", "approve", "forward")
# Approve-tier writes and the key each uses. Shown in TOOLS.md.
WRITES = {
    "pve_guest_power": "`POST /nodes/pve1/{qemu|lxc}/<vmid>/status/{start|shutdown|reboot}` with the separate token `power` of user `switchboard@pve` (role SwitchboardPower: VM.PowerMgmt + VM.Audit, set only on the allowlisted guests).",
    "jellyfin_library_scan": "`POST /Library/Refresh` with the Jellyfin key.",
}


NEVER_POWER = {"100", "101", "150", "160"}  # same list as config.rs NEVER_POWER


def power_vmids(spec):
    """The guests pve_guest_power may act on (tools.yaml power_vmids)."""
    v = [str(x) for x in spec.get("power_vmids") or []]
    assert v and all(x.isdigit() for x in v), "power_vmids must be digit strings"
    assert not set(v) & NEVER_POWER, "power_vmids holds a guest that may never be powered"
    return sorted(v, key=int)


HEADER = "# GENERATED by switchboard/gen.py from switchboard/tools.yaml. Do not edit by hand.\n"


def upstream_source(path):
    return Path(path).expanduser() if path.startswith("~") else REPO / path


def live_tools(spec, group):
    """The TOOLS list the gateway's tools/list returns, imported from its source without running it as a server."""
    src = upstream_source(spec["upstreams"][group]["source"]).resolve()
    root, mod = src.parent, [src.stem]
    while (root / "__init__.py").exists():  # inside a package: import it by its dotted name
        mod.insert(0, root.name)
        root = root.parent
    sys.path.insert(0, str(root))
    try:
        m = importlib.import_module(".".join(mod))
        return json.loads(json.dumps(m.TOOLS))
    finally:
        sys.path.remove(str(root))


def snapshot(spec, group):
    return json.loads((HERE / spec["upstreams"][group]["snapshot"]).read_text())


def snapshot_text(tools):
    return json.dumps(tools, indent=1, ensure_ascii=False) + "\n"


def forwarded(spec):
    """{tool: (group, upstream tool dict)} for every upstream tool, from the committed snapshots."""
    out = {}
    for group in sorted(spec.get("upstreams", {})):
        for t in snapshot(spec, group):
            assert t["name"] not in spec["tools"], f"upstream tool {t['name']} clashes with a switchboard tool"
            assert t["name"] not in out, f"upstream tool {t['name']} is in two upstreams"
            out[t["name"]] = (group, t)
    return out


def load():
    spec = yaml.safe_load((HERE / "tools.yaml").read_text())
    for a, c in spec["agents"].items():
        assert c.get("binary", "").startswith("/"), f"agent {a}: binary (the one program allowed to use the door) required"
        for group, be in (c.get("forward") or {}).items():
            assert spec["backends"][be]["group"] == group, f"agent {a}: backend {be} does not serve {group}"
            assert bool(spec["backends"][be].get("eval")) == bool(c.get("eval")), f"agent {a}: eval agents reach eval backends only, and only they do"
    for group, u in (spec.get("upstreams") or {}).items():
        for a in u["agents"]:
            assert group in (spec["agents"][a].get("forward") or {}), f"upstream {group}: agent {a} has no forward.{group}"
    for name, t in spec["tools"].items():
        assert t["tier"] in TIERS, f"{name}: tier {t['tier']} not supported"
        for a in t.get("agents", []):
            assert a in spec["agents"], f"{name}: unknown agent {a}"
        assert t.get("backend", "prometheus") in BACKENDS, f"{name}: unknown backend {t.get('backend')}"
        for arg, s in (t.get("args") or {}).items():
            assert s.get("type") == "string" and s.get("pattern"), f"{name}.{arg}: string with a pattern required"
    return spec


def agent_tools(spec, agent):
    own = [n for n, t in spec["tools"].items() if agent in t.get("agents", [])]
    fwd = [n for n, (g, _) in forwarded(spec).items() if agent in spec["upstreams"][g]["agents"]]
    return sorted(own + fwd)


def agents_json(spec):
    tools = {
        n: {"tier": t["tier"], "description": t["description"], "args": t.get("args") or {}}
        for n, t in sorted(spec["tools"].items())
    }
    for n, (g, t) in forwarded(spec).items():
        tools[n] = {"tier": "forward", "upstream": g, "description": t["description"], "input_schema": t["inputSchema"], "args": {}}
    agents = {}
    for a, cfg in sorted(spec["agents"].items()):
        agents[a] = {"tools": agent_tools(spec, a), "rate_per_min": cfg["rate_per_min"]}
        if cfg.get("forward"):
            agents[a]["forward"] = dict(sorted(cfg["forward"].items()))
        if cfg.get("eval"):
            agents[a]["eval"] = True
    backends = {n: {k: b[k] for k in sorted(b)} for n, b in sorted((spec.get("backends") or {}).items())}
    out = {"_generated": "switchboard/gen.py from tools.yaml", "tools": dict(sorted(tools.items())), "agents": agents, "backends": backends}
    if "pve_guest_power" in spec["tools"]:
        out["power_vmids"] = power_vmids(spec)
    return json.dumps(out, indent=1, sort_keys=True) + "\n"


def profile(spec, agent):
    a, sb = spec["agents"][agent], spec["switchboard"]
    tools = agent_tools(spec, agent)
    # Written in the exact shape `openshell profile export` returns, so drift-check's equality test holds.
    rules = ["      - allow:\n          method: %s" % m for m in ("initialize", "notifications/initialized", "tools/list", "ping")]
    rules += ["      - allow:\n          method: tools/call\n          params:\n            name:\n              glob: %s" % t for t in tools]
    versions = ", ".join(f'"{v}"' for v in sorted(sb["mcp_versions"]))
    return HEADER + f"""id: {a['provider']}
resource_version: 1
display_name: {a['provider']} (switchboard door for {agent})
description: >-
  Bearer token for the switchboard ({sb['host']}:{sb['port']}). The value lives only in the secrets manager
  ({a['secret_name']}); the switchboard keeps only its sha256. protocol mcp: OpenShell itself passes only
  these {len(tools)} tool names, and the switchboard re-checks token -> tools. Source: switchboard/tools.yaml.
category: agent
credentials:
  - name: switchboard_token
    description: switchboard bearer token for {agent}
    env_vars:
      - {a['env_var']}
    required: true
    auth_style: bearer
    header_name: authorization
    query_param: ""
endpoints:
  - host: {sb['host']}
    port: {sb['port']}
    protocol: mcp
    mcp:
      versions: [{versions}]
    enforcement: enforce
    allowed_ips: [{sb['host']}/32]
    rules:
""" + "\n".join(rules) + """
binaries:
  - """ + a["binary"] + """
inference_capable: false
source: user
scope: workspace
"""


def tools_md(spec):
    lines = [
        "<!-- GENERATED by switchboard/gen.py from switchboard/tools.yaml. Do not edit by hand. -->",
        "# Switchboard buttons",
        "",
        "Every tool the switchboard offers, who may press it, and what happens when they do.",
        "**read** = runs on its own and is logged. **approve** = posts a request to the Discord approvals channel, @-mentions the approver, and returns a request id at once; it runs only on the approver's own ✅ (or passkey approval) within 30 minutes (their ❌ denies; anyone else's reaction, the bot's included, is ignored). Max 3 pending per agent; a restart expires anything pending.",
        "",
        "| Tool | Tier | Backend | Agents | What it does | Arguments |",
        "|---|---|---|---|---|---|",
    ]
    for n, t in sorted(spec["tools"].items()):
        args = ", ".join(f"`{k}` ({v.get('description', '')})" for k, v in (t.get("args") or {}).items()) or "none"
        lines.append(f"| `{n}` | {t['tier']} | {t.get('backend', 'prometheus')} | {', '.join(t.get('agents', []))} | {t['description']} | {args} |")
    for n, (g, t) in sorted(forwarded(spec).items()):
        args = ", ".join(f"`{k}`" for k in t["inputSchema"].get("properties", {})) or "none"
        desc = t["description"].replace("|", "/").replace("\n", " ")
        lines.append(f"| `{n}` | forward | {g} gateway | {', '.join(spec['upstreams'][g]['agents'])} | {desc} | {args} |")
    lines += ["", "## Approve-tier writes", ""]
    lines += [f"- **`{n}`**: {d}" for n, d in WRITES.items() if n in spec["tools"]]
    if "pve_guest_power" in spec["tools"]:
        lines += ["", f"Guests `pve_guest_power` may act on (`power_vmids` in `tools.yaml`): {', '.join(power_vmids(spec))}. "
                  "Never: 100 workstation, 101 secrets vault, 150 agent host, 160 switchboard (refused by the config check too)."]
    lines += ["", "## Backends and their keys", "", "Keys live in the secrets manager and on the switchboard host in `/etc/switchboard/secrets.env` (root, 0600), loaded as a systemd credential. No agent box ever holds one.", ""]
    lines += [f"- **{b}**: {d}" for b, d in BACKENDS.items()]
    lines += ["", "## Forwarded tools (tier forward)", "",
              "Passed on unchanged to the agent's own MCP gateway, which keeps every guard of its own (its own rate limits and "
              "propose-only writes). The switchboard adds token -> tools "
              "-> backend (an agent reaches only the backend its `forward` names) and in-flight caps. Schemas are byte-identical to the "
              "gateway's tools/list (`upstream/<group>.json`, `gen.py --check-upstream`).", "",
              "| Backend | Group | URL | Key | Timeout | Slow tools | In flight |", "|---|---|---|---|---|---|---|"]
    if not spec.get("backends"):
        lines[-2:] = ["None configured in this example."]
    for n, b in sorted((spec.get("backends") or {}).items()):
        slow = ", ".join(f"{k} {v}s" for k, v in sorted((b.get("slow") or {}).items())) or "none"
        cap = ", ".join(f"{k} {v}" for k, v in sorted((b.get("max_inflight") or {}).items())) or "default 4"
        lines.append(f"| `{n}` | {b['group']} | `{b['url']}` | `{b['token_env']}` | {b['timeout_secs']}s | {slow} | {cap} |")
    lines += ["", "## Agents", "", "| Agent | Box | Provider | Env var in the box | Forwards to | Rate limit |", "|---|---|---|---|---|---|"]
    for a, c in sorted(spec["agents"].items()):
        fwd = ", ".join(f"{g} -> `{b}`" for g, b in sorted((c.get("forward") or {}).items())) or "none"
        lines.append(f"| {a} | `{c['box']}` | `{c['provider']}` | `{c['env_var']}` | {fwd} | {c['rate_per_min']}/min |")
    return "\n".join(lines) + "\n"


def check_upstream(spec):
    diffs = 0
    for group in sorted(spec.get("upstreams", {})):
        want, have = snapshot_text(live_tools(spec, group)), (HERE / spec["upstreams"][group]["snapshot"]).read_text()
        d = list(difflib.unified_diff(have.splitlines(), want.splitlines(), f"snapshot/{group}", f"live/{group}", lineterm="", n=1))
        n = sum(1 for l in d if l[:1] in "+-" and not l.startswith(("+++", "---")))
        print(f"upstream {group}: {len(json.loads(want))} tools, {n} differing lines")
        for l in d[:40]:
            print("   " + l)
        diffs += n
    print(f"CHECK-UPSTREAM diffs={diffs}")
    return 1 if diffs else 0


def main():
    if "--check-upstream" in sys.argv[1:]:
        sys.exit(check_upstream(yaml.safe_load((HERE / "tools.yaml").read_text())))
    if "--sync-upstream" in sys.argv[1:]:
        spec = yaml.safe_load((HERE / "tools.yaml").read_text())
        for group, u in sorted(spec.get("upstreams", {}).items()):
            path = HERE / u["snapshot"]
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(snapshot_text(live_tools(spec, group)))
            print(f"wrote {path.relative_to(REPO)}")
        return
    spec = load()
    out = {HERE / "generated" / "agents.json": agents_json(spec), HERE / "TOOLS.md": tools_md(spec)}
    for agent, c in spec["agents"].items():
        out[REPO / "boxes" / c["box"] / "openshell" / f"profile-{c['provider']}.yaml"] = profile(spec, agent)
    if "--check" in sys.argv[1:]:
        stale = [p for p, text in out.items() if not p.exists() or p.read_text() != text]
        for p in stale:
            print(f"stale {p.relative_to(REPO)}")
        print(f"GEN-CHECK files={len(out)} stale={len(stale)}")
        sys.exit(1 if stale else 0)
    for path, text in out.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"wrote {path.relative_to(REPO)}")


if __name__ == "__main__":
    main()
